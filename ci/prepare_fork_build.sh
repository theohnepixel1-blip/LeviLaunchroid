#!/usr/bin/env bash
# Prepares a CI checkout of a fork that has no private Discord SDK or Firebase config.
# It edits the checkout only; nothing here is committed back.
set -euo pipefail

# 1. Discord SDK. libgxcore.so (needed to start Minecraft) links against
#    libdiscord_partner_sdk.so, so build a do-nothing library with the same symbols.
#    Discord Rich Presence is disabled in this build (application id 0).
stub=app/src/main/cpp/discord_stub
mkdir -p "$stub"
symbols=$(readelf --dyn-syms -W app/src/main/jniLibs/arm64-v8a/libgxcore.so |
  awk '$7 == "UND" && $8 ~ /^Discord_/ { sub(/@.*/, "", $8); print $8 }' | sort -u)
[ -n "$symbols" ] || { echo "No Discord symbols found in libgxcore.so" >&2; exit 1; }
{
  echo '// Generated by ci/prepare_fork_build.sh'
  for s in $symbols; do
    echo "extern \"C\" __attribute__((visibility(\"default\"))) long $s() { return 0; }"
  done
} > "$stub/stub.cpp"
cat >> app/src/main/cpp/CMakeLists.txt <<'CMAKE'

add_library(discord_partner_sdk SHARED discord_stub/stub.cpp)
CMAKE

# The one Java class the launcher imports from the SDK.
java=app/src/main/java/com/discord/socialsdk
mkdir -p "$java"
cat > "$java/DiscordSocialSdkInit.java" <<'JAVA'
package com.discord.socialsdk;

public final class DiscordSocialSdkInit {
    private DiscordSocialSdkInit() {}

    public static void setEngineActivity(android.app.Activity activity) {}
}
JAVA
sed -i '/discord_partner_sdk\.aar/d' app/build.gradle

# 2. Placeholder Firebase config. The API key must look well formed (39 characters,
#    starting "A") or Firebase can crash the app at runtime. Push news will not work.
if [ ! -f app/google-services.json ]; then
  cat > app/google-services.json <<'JSON'
{
  "project_info": {
    "project_number": "000000000000",
    "project_id": "ci-placeholder",
    "storage_bucket": "ci-placeholder.appspot.com"
  },
  "client": [
    {
      "client_info": {
        "mobilesdk_app_id": "1:000000000000:android:0000000000000000",
        "android_client_info": { "package_name": "org.levimc.launcher" }
      },
      "oauth_client": [],
      "api_key": [ { "current_key": "A00000000000000000000000000000000000000" } ],
      "services": { "appinvite_service": { "other_platform_oauth_client": [] } }
    }
  ],
  "configuration_version": "1"
}
JSON
fi

# 3. Hide the Discord Rich Presence setting. The views stay in the layout (the
#    settings code still looks them up), they are just not shown.
python3 - <<'PY'
import re

path = "app/src/main/res/layout/view_settings_sections.xml"
text = open(path, encoding="utf-8").read()
switch = text.index('android:id="@+id/switch_discord_presence"')
text_block = text.rindex('style="@style/settings_RowText"', 0, switch)
row = text.rindex('style="@style/settings_Row"', 0, text_block)
divider = text.rindex('style="@style/settings_Divider"', 0, row)
for start in (row, divider):  # later position first, so earlier offsets stay valid
    text = text[:start] + 'android:visibility="gone"\n' + text[start:]
open(path, "w", encoding="utf-8").write(text)
PY
python3 ci/ui_changes.py
python3 ci/ui_changes_2.py
python3 ci/ui_changes_3.py
python3 ci/ui_changes_4.py
python3 ci/ui_changes_5.py
python3 ci/ui_changes_6.py
python3 ci/ui_changes_7.py
python3 ci/ui_changes_8.py
